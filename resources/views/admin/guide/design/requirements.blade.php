<section>
    <h2 id="requirements-definition">1. 要件定義</h2>
    <ul class="guide-steps">
        <h3 id="project-overview">1-1.プロジェクトの概要</h3>
        <p>本システムは、従来バラバラに管理されていた「社員情報」「勤怠記録」「経費精算」を統合し、</br>
            事務作業の効率化とデータの整合性向上を実現するための Web アプリケーションである。</p>

        <h3 id="purpose-of-systemization">1-2.システム化の目的</h3>
        <p>システム化の目的は、業務の効率化とデータの整合性向上を実現することである。</p>
        <ul>
            <li>ペーパーレス化: 紙や Excel による申請を廃止し、デジタル化する。</li>
            <li>承認フローの迅速化: 申請から承認までのステータスを可視化し、停滞を防ぐ。</li>
            <li>データの一元管理: 給与計算に必要な勤怠・経費データを一括出力可能にする。</li>
            <li>改ざん防止: 確定後のデータをロックし、信頼性の高いエビデンスを確保する。</li>
        </ul>

        <h3 id="business-requirements">1-3.業務要件（機能要件）</h3>
        <ul>
            <li>1-3-1.社員管理機能</li>
            <ul>
                <li>社員情報の保持: 氏名、社員番号、部署、入社日、通勤費などの詳細項目を管理。</li>
                <li>アカウント制御: ログイン情報の管理および管理者権限（is_admin）の付与。</li>
                <li>論理削除: 誤操作防止のため、削除後もデータの復元を可能とする。</li>
            </ul>
            <li>1-3-2.勤怠管理機能</li>
            <ul>
                <li>打刻管理: 出退勤時刻、休憩時間、外出時間の記録。</li>
                <li>休暇・残業申請: 有給、特休、残業等の申請および承認ワークフロー。</li>
                <li>月次確定フロー: 本人が当月の勤務内容を確認し「確定（ロック申請）」を行う。</li>
                <li>管理者承認: 管理者が内容を精査し、最終的な「承認（編集不可）」を行う。</li>
            </ul>
            <li>1-3-3.経費精算管理機能</li>
            <ul>
                <li>経費登録: 発生日、費目（交通費、宿泊費、その他）、目的地、支払先、金額の記録。</li>
                <li>領収書管理: 領収書の有無の記録。</li>
                <li>精算計算: 支払済額（仮払い）を差し引いた、最終的な請求額の自動算出。</li>
                <li>承認・却下フロー: 管理者による承認、および却下時の「理由入力」の必須化。</li>
            </ul>
        </ul>
        <h3 id="system-configuration">1-4.システム構成・技術要件</h3>
        <ul>
            <li>プラットフォーム: Webブラウザ（レスポンシブ対応）</li>
            <li>バックエンド: PHP 8.x / Laravel 11.x</li>
            <li>フロントエンド: React / Blade テンプレート</li>
            <li>データベース: MySQL 8.x (文字コード: utf8mb4)</li>
            <li>インフラ: AWS (EC2, RDS)</li>
        </ul>
        <h3 id="security-requirements">1-5.権限・セキュリティ要件</h3>
        <ul>
            <li>権限分離: 「一般ユーザー」と「管理者」の 2 段階。</li>
            <ul>
                <li>一般ユーザー：自身のデータ閲覧・登録・申請のみ。</li>
                <li>管理者：全社員のデータ閲覧・編集・承認、マスタ管理。</li>
            </ul>
            <li>認証: メールアドレスとパスワードによる認証。</li>
            <li>セッション管理: 一定時間無操作の場合の自動ログアウト。</li>
        </ul>
        <h3 id="non-functional-requirements">1-6.非機能要件</h3>
        <ul>
            <li>可用性: AWS の冗長化構成を検討し、業務時間中のシステムダウンを最小限に抑える。</li>
            <li>整合性: 外部キー制約およびトランザクション処理により、データの不整合を防止。</li>
            <li>拡張性: 将来的な給与ソフトへの CSV 連携機能の追加を考慮した設計。</li>
        </ul>
        <h3 id="function-list">1-7.画面一覧（UI/UX要件）</h3>
        <ul>
            <li>トップページ: 今日の打刻状態、未処理の通知を表示するダッシュボード。</li>
            <li>勤務表画面: カレンダー形式またはリスト形式の入力画面。</li>
            <li>経費精算画面: 入力フォームと申請履歴の一覧。</li>
            <li>管理者メニュー: 各種承認および名簿管理へのリンク。</li>
            <li>操作ガイド: 初心者向けの図解マニュアル（PDF表示対応）。</li>
        </ul>
    </ul>
</section>
