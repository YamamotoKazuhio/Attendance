    <h2 id="basic-design">2. 基本設計</h2>
    <p>基本設計書は、要件定義書をもとに「業務管理システム」の基本設計書をまとめます。</br>
        このシステムは、Laravel（PHP）とReact（JavaScript）をベースに、AWSインフラ上での稼働を想定したフルスタック構成となっています。
    </p>
    <ol class="guide-steps">
        <li id="ui-design">2-1. システム概要</li>
        <p>本システムは、社員情報の一括管理、日々の勤怠打刻および申請承認、経費精算のワークフローを
            一元化し、バックオフィス業務の効率化を図ることを目的としています。</p>
        <p>開発スタック</p>
        <ul>
            <li>フレームワーク: Laravel (PHP), React</li>
            <li>データベース: MySQL (utf8 構成)</li>
            <li>インフラ: AWS (EC2, RDS, S3)</li>
            <li>デプロイ: GitHub Actions / AWS CodeDeploy による CI/CD</li>
        </ul>

        <li id="function-list">2-2. 機能一覧</li>
        <p>以下に、本システムの主要な機能を要件定義書に基づいてまとめます。</p>
        <ol>
            <li>社員名簿管理</li>
            <p>社員の基本情報および実務に必要な詳細情報を管理します。</p>
            <ul>
                <li>ユーザー管理: 標準認証によるログイン・アカウント制御。</li>
                <li>詳細情報管理: 社員番号、氏名（漢字・カナ）、部署、入社日、通勤費等の管理。</li>
                <li>管理者機能: 社員一覧の閲覧、情報の編集、アカウントの論理削除および復元。</li>
            </ul>

            <li>勤怠管理</li>
            <p>日々の出退勤打刻と、休暇・残業の申請フローを管理します。</p>
            <ul>
                <li>打刻機能: 出勤・退勤時刻の記録、休憩時間、外出時間の管理。</li>
                <li>申請フロー: 残業や休暇（有給・特休等）の申請。本人が「確定」することで管理者へ通知。</li>
                <li>承認ワークフロー: 管理者による申請内容の確認・承認・却下。</li>
            </ul>
        </ol>
    </ol>

