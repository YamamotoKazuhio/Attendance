    <h2 id="permission-design">4. 画面遷移・権限設計</h2>
    <p>本システムは、一般ユーザーと管理者の2段階の権限設計を採用しています。</br>
        一般ユーザーは自身のデータの閲覧・登録・申請のみが可能であり、</br>
        管理者は全社員のデータの閲覧・編集・承認、およびマスタ管理が可能です。
    </p>
    <h3 id="general-user-privileges">4.1 一般ユーザー権限</h3>
    <ol>
        <li>トップページ (Dashboard): 各種ステータス（今日の打刻、申請状況）の確認。</li>
        <li>勤務表画面: 打刻および月次確定申請。</li>
        <li>経費精算画面: 経費の登録・申請・履歴確認。</li>
        <li>操作ガイド: システム利用方法の閲覧。</li>
    </ol>

    <h3 id="administrator-privileges">4.2 管理者権限 (can:admin)</h3>
    <ul>
        <li>管理者メニュー (Selector): 各管理機能へのハブ。</li>
        <li>経費承認パネル: 全社員の経費精算を処理。</li>
        <li>勤務承認・月次報告: 勤怠データの承認と月次確定（一括ロック）。</li>
        <li>社員名簿管理: ユーザー情報の新規登録・編集・削除。</li>
    </ul>

    <h2 id="security-design">5. セキュリティ設計</h2>
    <p>本システムは、認可制御、データ保護、整合性の観点からセキュリティ設計を行っています。</p>
    <ul>
        <li>認可制御: ミドルウェアおよびゲートを用いた厳格な管理者権限チェック。</li>
        <li>データ保護: 論理削除の採用による誤操作時の復元対応。</li>
        <li>整合性: 月次確定後のデータ編集ロックによる改ざん防止。</li>
    </ul>
