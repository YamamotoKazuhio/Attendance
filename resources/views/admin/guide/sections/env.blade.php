<section>
    <h2 id="env">1. LaravelとReactについて</h2>
    IT開発における強力な2つのツール、LaravelとReactについて、それぞれの役割と関係性をわかりやすく解説します。
    一言でいうと、Laravelは「家の骨組みや水道・電気（裏側）」を作り、Reactは「おしゃれな内装や便利なスイッチ（表側）」を作る道具です。

    <h3 id="env-laravel">1-1. Laravel（ララベル）とは？</h3>
    <h4>役割：バックエンド（サーバーサイド）フレームワーク</h4>
    <p>Laravelは、PHPというプログラミング言語で動く、世界で最も人気のあるフレームワークの一つです。Webサイトが「動く」ために必要な「裏側の仕組み」を簡単に作れるように設計されています。</p>
    <h4>主な特徴</h4>
    <ul>
        <li>多機能: ログイン機能、データベース操作、メール送信など、Webアプリに必須の機能が最初から用意されています。</li>
        <li>書き方がきれい: 「職人のためのフレームワーク」と呼ばれ、コードが読みやすく、整理しやすいのが特徴です。</li>
        <li>高いセキュリティ: SQLインジェクションやクロスサイトスクリプティング（XSS）といった攻撃を防ぐ仕組みが標準で備わっています。</li>
    </ul>
    
    <h3 id="env-react">1-2. React（リアクト）とは？</h3>
    <h4>役割：フロントエンド（クライアントサイド）ライブラリ</h4>
    <p>Reactは、Meta（旧Facebook）が開発した、JavaScriptで「UI（ユーザーインターフェース）」を作るためのライブラリです。ブラウザ上で動く「見た目」と「操作感」をリッチにするために使われます。</p>
    <h4>主な特徴</h4>
    <ul>
        <li>コンポーネント化: 画面の部品（ボタン、入力欄、ヘッダーなど）をバラバラに作り、それをパズルのように組み合わせて画面を作ります。</li>
        <li>爆速な表示（仮想DOM）: 画面全体を読み直すのではなく、「変更があった場所だけ」を瞬時に書き換えるため、非常にスムーズに動きます。</li>
        <li>宣言的 UI: 「データがこうなったら、画面をこうしてね」と書くだけで、Reactが自動的に画面を更新してくれます。</li>
    </ul>
    
    <h3 id="env-relation">1-3. Laravel と React の関係</h3>
    <p>最近のWeb開発（今回の勤怠管理アプリなど）では、この2つを組み合わせて使うのが主流です。</br>
        <table border="1" cellpadding="10" cellspacing="0">
            <tr>
                <td>項目</td>
                <td>Laravel (バックエンド)</td>
                <td>React (フロントエンド)</td>
            </tr>
            <tr>
                <td>担当場所
                <td>サーバーの中</td>
                <td>ユーザーのブラウザ</td>
            </tr>
            <tr>
                <td>主な仕事
                <td>データの保存、計算、権限チェック</td>
                <td>画面の表示、ボタン操作、アニメーション</td>
            </tr>
            <tr>
                <td>例えるなら
                <td>レストランの厨房（料理を作る）</td>
                <td>レストランの接客（注文を聞き、料理を運ぶ）</td>
            </tr>
        </table>
